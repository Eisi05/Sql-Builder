package de.eisi05.sql.enums;

/**
 * Defines logical operators used for combining conditions in SQL queries (e.g., in WHERE clauses).
 */
public enum LogicOperator
{
    /**
     * Represents the logical AND operator. Both conditions must evaluate to true.
     */
    AND,

    /**
     * Represents the logical OR operator. At least one condition must evaluate to true.
     */
    OR
}
